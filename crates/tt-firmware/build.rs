//! Pick each image's link script, and tell it where its mailbox is.
//!
//! Every Tensix image uses `link.x` (T0's default reset PC) except the three role
//! images, which live in their own slots (`link_role_t{0,1,2}.x`,
//! `tt_isa::l1::roles`) so that one tile can hold all three role images and a
//! mover of up to `dm::IMAGE_MAX` at once, and the per-core probes
//! (`icache_t1`, `icache_t2`), which use their cores' default reset PCs. The
//! Ethernet image uses `link_e1.x`.
//! Per-binary link arguments are the only way to vary this within one crate.
//!
//! The mailbox base is a `--defsym` taken from `tt-isa` (a build-dependency), not
//! a number in a link script: the host polls the same constant, so the two cannot
//! drift. For the same reason the link scripts of B's mover (`link_b.x`) and of
//! the three role images (`link_role_t{0,1,2}.x`) are written here, into
//! `OUT_DIR`, from `tt_isa::dm::IMAGE_MAX` and `tt_isa::l1::roles`: resizing the
//! role slots is one constant, not five numbers to keep in step.

fn main() {
    let dir = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let out = std::env::var("OUT_DIR").unwrap();
    write_slot_scripts(std::path::Path::new(&out));
    // The generated scripts first; they `INCLUDE sections.x` from the manifest dir.
    println!("cargo:rustc-link-arg-bins=-L{out}");
    println!("cargo:rustc-link-arg-bins=-L{dir}");
    let tensix = [
        ("heartbeat", "link.x"),
        ("sfpu_mul", "link.x"),
        ("prng_seed", "link.x"),
        ("corpus", "link.x"),
        ("corpus_t0", "link.x"),
        ("role_t0", "link_role_t0.x"),
        ("role_t1", "link_role_t1.x"),
        ("role_t2", "link_role_t2.x"),
        // The role runner with guarded runs, at the cores' default reset PCs
        // (`corpus::run_guarded_role`; `tt_kernels::atomics` loads them).
        ("guarded_t0", "link.x"),
        ("guarded_t1", "link_t1.x"),
        ("guarded_t2", "link_t2.x"),
    ];
    for (bin, script) in tensix {
        link(bin, script, tt_isa::mailbox::MAILBOX_BASE);
    }
    link("eth_e1", "link_e1.x", tt_isa::eth::MAILBOX_BASE);
    link("dm_b", "link_b.x", tt_isa::dm::MAILBOX_BASE);
    link("nc_probe", "link_nc.x", tt_isa::dm::nc::MAILBOX_BASE);
    link("dm_nc", "link_nc.x", tt_isa::dm::nc::MAILBOX_BASE);
    link("icache_b", "link_b.x", tt_isa::mailbox::MAILBOX_BASE);
    link("tag_search_b", "link_b.x", tt_isa::mailbox::MAILBOX_BASE);
    link("noc_probe_b", "link_b.x", tt_isa::mailbox::MAILBOX_BASE);
    link("read_loop_b", "link_b.x", tt_isa::mailbox::MAILBOX_BASE);
    link("icache_nc", "link_nc.x", tt_isa::dm::nc::MAILBOX_BASE);
    for (bin, script, t) in [
        ("icache_t0", "link.x", 0),
        ("icache_t1", "link_t1.x", 1),
        ("icache_t2", "link_t2.x", 2),
    ] {
        link(
            bin,
            script,
            tt_isa::mailbox::role::BASE + t * tt_isa::mailbox::role::STRIDE,
        );
    }
    // The `.ttinsn` experiment image, linked as the T1 role image is
    // (`docs/plans/ttinsn-push-experiment.md`). Only when the feature is on: cargo
    // refuses link arguments for a binary it is not building.
    if std::env::var_os("CARGO_FEATURE_TTINSN_EXPERIMENT").is_some() {
        link("ttinsn_t1", "link_role_t1.x", tt_isa::mailbox::MAILBOX_BASE);
    }
    for f in [
        "link.x",
        "link_t1.x",
        "link_t2.x",
        "link_e1.x",
        "link_nc.x",
        "sections.x",
    ] {
        println!("cargo:rerun-if-changed={f}");
    }
}

fn link(bin: &str, script: &str, mailbox: u64) {
    println!("cargo:rustc-link-arg-bin={bin}=-T{script}");
    println!("cargo:rustc-link-arg-bin={bin}=--defsym=__mailbox={mailbox:#x}");
}

/// Write `link_b.x` and `link_role_t{0,1,2}.x` into `out`, from the constants the
/// host loads and checks the images against.
fn write_slot_scripts(out: &std::path::Path) {
    use tt_isa::{dm, l1::roles};
    const LOCAL: &str = "  LOCAL (rw)  : ORIGIN = 0xFFB00000, LENGTH = 4K";
    let b = format!(
        "/* Generated by tt-firmware/build.rs: the RISCV B data mover (`dm_b`).\n \
         * B's entry point is hardwired to L1 offset 0 and it has no reset-PC\n \
         * override, so the image lives at 0 and may grow up to the first role\n \
         * slot (`tt_isa::dm::IMAGE_MAX`): past it the link fails rather than\n \
         * clobbering T0's role image. */\n\
         MEMORY\n{{\n  L1    (rwx) : ORIGIN = {:#010X}, LENGTH = {:#X}\n{LOCAL}\n}}\n\n\
         INCLUDE sections.x\n",
        dm::IMAGE_BASE,
        dm::IMAGE_MAX
    );
    std::fs::write(out.join("link_b.x"), b).expect("write link_b.x");
    for (t, base) in roles::BASE.iter().enumerate() {
        let role = format!(
            "/* Generated by tt-firmware/build.rs: the T{t} role image, in its slot of\n \
             * `tt_isa::l1::roles` (`roles::BASE[{t}]`, `roles::SLOT` long), reached\n \
             * through T{t}'s reset-PC override. The slots are packed against NC's\n \
             * slot, so B's mover keeps everything below them. */\n\
             MEMORY\n{{\n  L1    (rwx) : ORIGIN = {base:#010X}, LENGTH = {:#X}\n{LOCAL}\n}}\n\n\
             INCLUDE sections.x\n",
            roles::SLOT
        );
        std::fs::write(out.join(format!("link_role_t{t}.x")), role)
            .unwrap_or_else(|e| panic!("write link_role_t{t}.x: {e}"));
    }
}
