//! Ports of the Vector Unit's documented functional models, beyond `SFPMAD`'s
//! (which is [`super::fma_bh`]).
//!
//! Each is a function of one lane's bits, transcribed from its instruction
//! page, and held to the page's own C -- extracted from the pinned tree and
//! compiled by `tt-tests/build.rs`, as `fma.c` is -- by `sfpu_models_oracle`.
//! The lookup tables were copied out of the page by script, not by hand, and
//! the oracle compares every input that reaches them.

/// `SFPARECIP.md`'s `ApproxRecip`: a reciprocal good to `0.9944 < r·x <
/// 1.0054` for `2^-126 <= x < 2^126` (a positive FP32), infinity below that
/// range and zero above it. The seed for a Newton refinement.
pub const fn approx_recip(x: u32) -> u32 {
    if x < 0x0080_0000 {
        0x7f80_0000
    } else if x < 0x7e80_0000 {
        ((253 - (x >> 23)) << 23) | ((RECIP_LUT[((x >> 16) & 0x7f) as usize] as u32) << 16)
    } else {
        0
    }
}

/// `SFPARECIP.md`'s `ApproxExp`: `e^x` to `0.9922 < r/e^x < 1.016` for
/// `0 <= x < 2` (a positive FP32), and nothing useful from 2 up.
pub const fn approx_exp(x: u32) -> u32 {
    if x < 0x0080_0000 {
        0x3f80_0000
    } else if x < 0x3c80_0000 {
        0x3f81_0000 | (x & 0xffff)
    } else if x < 0x3f32_0000 {
        0x3f80_0000 | ((EXP_LUT[((x >> 16) - 0x3c80) as usize] as u32) << 16) | (x & 0xffff)
    } else if x < 0x4000_0000 {
        0x4000_0000 | ((EXP_LUT[((x >> 16) - 0x3c80) as usize] as u32) << 16) | (x & 0xffff)
    } else {
        0x4080_0000 | (x & 0xffff)
    }
}

/// `SFPARECIP`'s modes (`SFPARECIP_MOD1_*`).
pub mod arecip_mod1 {
    pub const RECIP: u32 = 0;
    pub const COND_RECIP: u32 = 1;
    pub const EXP: u32 = 2;
}

/// One lane of `SFPARECIP`: `c` is `LReg[VC]`, `b` is `LReg[VB]` (read only by
/// `COND_RECIP`), `d` the lane's old `LReg[VD]` (kept by `COND_RECIP` where
/// `b` is not negative). Any `mod1` past `EXP` acts as `EXP`.
pub const fn arecip(mod1: u32, b: u32, c: u32, d: u32) -> u32 {
    let sign = c & 0x8000_0000;
    match mod1 {
        arecip_mod1::RECIP => sign + approx_recip(c - sign),
        arecip_mod1::COND_RECIP => {
            if (b as i32) < 0 {
                approx_recip(c - sign)
            } else {
                d
            }
        }
        _ => sign + approx_exp(c - sign),
    }
}

