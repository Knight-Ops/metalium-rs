#[cfg(test)]
mod tests {
    use super::*;

    /// The page's own spot values.
    #[test]
    fn the_page_s_examples() {
        assert_eq!(approx_recip(1.0f32.to_bits()), 0.996_093_75f32.to_bits());
        assert_eq!(approx_exp(1.0f32.to_bits()), 2.703_125f32.to_bits());
        assert_eq!(
            arecip(arecip_mod1::RECIP, 0, (-1.0f32).to_bits(), 0),
            (-0.996_093_75f32).to_bits()
        );
    }

    /// The page's accuracy claims, over every input the tables reach.
    #[test]
    fn the_page_s_bounds_hold() {
        for hi in 0x0080u32..0x7e80 {
            for lo in [0u32, 0x8000, 0xffff] {
                let x = (hi << 16) | lo;
                let r = f32::from_bits(approx_recip(x)) as f64 * f32::from_bits(x) as f64;
                assert!(0.9944 < r && r < 1.0054, "{x:#x}: {r}");
            }
        }
        for hi in 0x0080u32..0x4000 {
            let x = (hi << 16) | 0x1234;
            let e = (f32::from_bits(x) as f64).exp();
            let r = f32::from_bits(approx_exp(x)) as f64 / e;
            assert!(0.9922 < r && r < 1.016, "{x:#x}: {r}");
        }
    }
}
