//! Fixed prompt sets with HuggingFace's teacher-forced predictions over them, and how a model's
//! predictions agree with them: the performance contract's model gate (ADR 0006,
//! `crates/tt-tests/tests/step269_performance_contract.rs`).
//!
//! A [`Case`] is a chat-templated prompt and HuggingFace's greedy continuation of it, with
//! HuggingFace's five largest logits at every position that predicts a continuation token. A model
//! is run teacher-forced over the same tokens (each position sees the reference's tokens, never its
//! own), and [`agreement`] says how often its top-1 is HuggingFace's top-1, how often HuggingFace's
//! top-1 is among its top five, and how its full logits correlate with another model's (burn-flex
//! in F32, which `tests/llama_1_7b_host.rs` holds to HuggingFace over the same set).

// Generated by `reference/llama_reference.py --prompt-set`: kept as written.
#[rustfmt::skip]
pub mod smollm2_1_7b;

/// One prompt of a set and HuggingFace's teacher-forced reference over it.
#[derive(Clone, Copy, Debug)]
pub struct Case {
    /// The user's message, before the chat template.
    pub chat: &'static str,
    /// The chat-templated prompt's ids, the assistant's turn opened.
    pub prompt: &'static [i32],
    /// HuggingFace's greedy continuation (ending at the end-of-turn token if it came first).
    pub continuation: &'static [i32],
    /// At each position that predicts `continuation[i]` (the prompt's last, then each
    /// continuation token but the last), the five largest logits' ids, largest first.
    pub top5: &'static [[i32; 5]],
    /// Those five logits.
    pub logits: &'static [[f32; 5]],
}

/// The index of the largest of `v`, the first of equals.
pub fn argmax(v: &[f32]) -> usize {
    top_k(v, 1)[0]
}

/// The indices of the `k` largest of `v`, largest first, the first of equals first.
pub fn top_k(v: &[f32], k: usize) -> Vec<usize> {
    let mut order: Vec<usize> = (0..v.len()).collect();
    order.sort_by(|&a, &b| v[b].total_cmp(&v[a]).then(a.cmp(&b)));
    order.truncate(k);
    order
}

/// Pearson's correlation of `a` and `b`, in f64.
pub fn pearson(a: &[f32], b: &[f32]) -> f64 {
    assert_eq!(a.len(), b.len(), "correlated vectors of one length");
    let n = a.len() as f64;
    let (ma, mb) = (
        a.iter().map(|&x| x as f64).sum::<f64>() / n,
        b.iter().map(|&x| x as f64).sum::<f64>() / n,
    );
    let (mut ab, mut aa, mut bb) = (0f64, 0f64, 0f64);
    for (&x, &y) in a.iter().zip(b) {
        let (x, y) = (x as f64 - ma, y as f64 - mb);
        ab += x * y;
        aa += x * x;
        bb += y * y;
    }
    ab / (aa * bb).sqrt()
}

/// How a model's teacher-forced predictions agree with a set's reference.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Agreement {
    /// Positions compared.
    pub positions: usize,
    /// The share of positions whose top-1 is HuggingFace's top-1.
    pub top1: f64,
    /// The share of positions where HuggingFace's top-1 is among the model's five largest.
    pub top5: f64,
    /// The mean, over positions, of the full logits' correlation with the PCC reference's.
    pub pcc_mean: f64,
    /// The least of those correlations.
    pub pcc_min: f64,
}

/// `got[c][i]`, the model's logits at case `c`'s position `i` (as [`Case::top5`] numbers them),
/// against `cases`' reference, and its correlation with `pcc_reference` at the same positions.
pub fn agreement(
    cases: &[Case],
    got: &[Vec<Vec<f32>>],
    pcc_reference: &[Vec<Vec<f32>>],
) -> Agreement {
    assert_eq!(got.len(), cases.len(), "a run of every case");
    assert_eq!(
        pcc_reference.len(),
        cases.len(),
        "a reference run of every case"
    );
    let (mut positions, mut top1, mut top5) = (0usize, 0usize, 0usize);
    let (mut pcc_sum, mut pcc_min) = (0f64, f64::INFINITY);
    for ((case, got), reference) in cases.iter().zip(got).zip(pcc_reference) {
        assert_eq!(
            got.len(),
            case.top5.len(),
            "{:?}: every position",
            case.chat
        );
        assert_eq!(
            reference.len(),
            case.top5.len(),
            "{:?}: every position",
            case.chat
        );
        for ((logits, hf), reference) in got.iter().zip(case.top5).zip(reference) {
            let want = hf[0] as usize;
            positions += 1;
            top1 += usize::from(argmax(logits) == want);
            top5 += usize::from(top_k(logits, 5).contains(&want));
            let r = pearson(logits, reference);
            pcc_sum += r;
            pcc_min = pcc_min.min(r);
        }
    }
    let n = positions as f64;
    Agreement {
        positions,
        top1: top1 as f64 / n,
        top5: top5 as f64 / n,
        pcc_mean: pcc_sum / n,
        pcc_min,
    }
}

impl std::fmt::Display for Agreement {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "{} positions: top-1 {:.2}%, top-5 {:.2}%, PCC mean {:.6} (least {:.6})",
            self.positions,
            100.0 * self.top1,
            100.0 * self.top5,
            self.pcc_mean,
            self.pcc_min
        )
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn ties_take_the_first_and_pearson_is_scale_free() {
        assert_eq!(argmax(&[1.0, 3.0, 3.0, 2.0]), 1);
        assert_eq!(top_k(&[1.0, 3.0, 3.0, 2.0, 3.0], 3), vec![1, 2, 4]);
        let a = [1.0, 2.0, 4.0, -1.0];
        let b: Vec<f32> = a.iter().map(|x| 3.0 * x - 7.0).collect();
        assert!((pearson(&a, &b) - 1.0).abs() < 1e-12);
        let c: Vec<f32> = a.iter().map(|x| -x).collect();
        assert!((pearson(&a, &c) + 1.0).abs() < 1e-12);
    }

    #[test]
    fn agreement_counts_top1_top5_and_correlation() {
        const CASES: [Case; 1] = [Case {
            chat: "",
            prompt: &[0],
            continuation: &[2, 0],
            top5: &[[2, 1, 0, 3, 4], [0, 1, 2, 3, 4]],
            logits: &[[0.0; 5], [0.0; 5]],
        }];
        let reference = vec![vec![
            vec![0.0, 1.0, 9.0, 0.5, 0.2, 0.1],
            vec![9.0, 1.0, 0.0, 0.5, 0.2, 0.1],
        ]];
        // Position 0 agrees; position 1's top-1 is index 1, HuggingFace's (0) only second.
        let got = vec![vec![
            vec![0.0, 1.0, 9.0, 0.5, 0.2, 0.1],
            vec![8.0, 9.0, 0.0, 0.5, 0.2, 0.1],
        ]];
        let a = agreement(&CASES, &got, &reference);
        assert_eq!((a.positions, a.top1, a.top5), (2, 0.5, 1.0));
        assert!((a.pcc_min - pearson(&got[0][1], &reference[0][1])).abs() < 1e-15);
        assert!(a.pcc_min < a.pcc_mean && a.pcc_mean < 1.0);
    }
}
